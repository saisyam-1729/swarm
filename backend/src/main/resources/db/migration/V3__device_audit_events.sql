-- Device lifecycle audit trail. Additive only; does not alter devices or telemetry tables.
-- Secrets and plaintext passwords must never be written here.

CREATE TABLE device_audit_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id    BIGINT,
    device_uid   VARCHAR(128) NOT NULL,
    tenant_id    UUID,
    plant_id     BIGINT,
    action       VARCHAR(64) NOT NULL,
    actor        VARCHAR(255),
    detail       VARCHAR(1024),
    created_at   TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_device_audit_device ON device_audit_events (device_id);
CREATE INDEX idx_device_audit_uid ON device_audit_events (device_uid);
